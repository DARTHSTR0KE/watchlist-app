-- Brings the database in line with the app: games and truth or dare.
-- One block, safe to run more than once.
--
-- 1. game_scores already existed in an older shape (one row per game
--    played, with a score column). The app keeps one row per person per
--    game. The old table is renamed to game_scores_legacy, not dropped,
--    so nothing in it is lost, and the right one is created below.
-- 2. td_turns never got created, so everything from truth-or-dare.sql
--    is applied again. Parts that already exist are left as they are.

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'game_scores' and column_name = 'score'
  ) and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'game_scores' and column_name = 'best_score'
  ) then
    if to_regclass('public.game_scores_legacy') is not null then
      raise exception 'game_scores_legacy already exists: stopping, nothing changed';
    end if;
    alter table public.game_scores rename to game_scores_legacy;
    -- Nobody reads it through the API any more.
    alter table public.game_scores_legacy enable row level security;
    revoke all on public.game_scores_legacy from anon, authenticated;
  end if;
end $$;

